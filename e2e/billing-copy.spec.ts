import { test, expect, type Page } from "@playwright/test";
import { LEGAL_VERSION } from "../client/src/lib/legal";

// Landing, Help and /plus must describe Plus the way the server is actually
// configured. The server's public config is embedded in each HTML response,
// so each state is simulated by rewriting it (and /api/billing/config, which
// /plus reads for prices) — no Stripe keys or env changes involved.

type State = { name: "disabled" | "test" | "live"; enabled: boolean; mode: "test" | "live" };
const STATES: State[] = [
  { name: "disabled", enabled: false, mode: "test" },
  { name: "test", enabled: true, mode: "test" },
  { name: "live", enabled: true, mode: "live" },
];
const PRICES = { month: { amount: 9.99, currency: "USD" }, year: { amount: 59.99, currency: "USD" } };

async function simulate(page: Page, state: State) {
  await page.addInitScript((version) => {
    localStorage.setItem("sadhana.legalAck", JSON.stringify({ version, acceptedAt: new Date().toISOString() }));
    localStorage.setItem("sadhana.welcome.seen", "1");
    localStorage.setItem("sadhana.onboarding.done", "1");
  }, LEGAL_VERSION);
  await page.route("**/*", async (route) => {
    if (route.request().resourceType() !== "document") return route.fallback();
    const res = await route.fetch();
    const html = (await res.text()).replace(
      /(<script type="application\/json" id="public-config">)([\s\S]*?)(<\/script>)/,
      (_m, open: string, json: string, close: string) =>
        open + JSON.stringify({ ...JSON.parse(json), billingEnabled: state.enabled, stripeMode: state.mode }) + close,
    );
    return route.fulfill({ response: res, body: html });
  });
  await page.route("**/api/billing/config", (route) => route.fulfill({ json: {
    enabled: state.enabled, testMode: state.mode === "test", portalAvailable: state.enabled, note: "",
    ...(state.enabled ? { prices: PRICES } : {}),
  } }));
}

const EXPECT = {
  disabled: { billing: /purchasing is unavailable/i, not: /test mode|no real charges|waitlist|planned/i },
  test: { billing: /Stripe test mode[\s\S]*no real charges/i, not: /unavailable|waitlist|planned/i },
  live: { billing: /\$9\.99\/month or \$59\.99\/year/, not: /test mode|no real charges|unavailable|waitlist|planned/i },
} as const;

for (const state of STATES) {
  test.describe(`billing ${state.name}`, () => {
    test.beforeEach(({ page }) => simulate(page, state));

    test("landing describes Plus and the AI classes accurately", async ({ page }) => {
      await page.goto("/welcome");
      const plus = page.getByTestId("landing-plus-billing");
      await expect(plus).toHaveAttribute("data-billing-state", state.name);
      await expect(plus).toContainText(EXPECT[state.name].billing);
      await expect(page.getByTestId("landing-free-list")).not.toContainText(EXPECT[state.name].not);
      if (state.name !== "live") await expect(plus).toContainText("$9.99/month or $59.99/year");
      await expect(page.getByTestId("landing-no-filmed-instruction")).toContainText("AI-generated instructor motion");
      const faq = page.locator("#faq");
      await expect(faq).toContainText("Can I buy Sadhana Plus?");
      await expect(faq).not.toContainText(/no video of a teacher/i);
      const classes = faq.locator("details", { hasText: /video classes taught by a real instructor/i });
      await classes.locator("summary").click();
      await expect(classes).toContainText("No human instructor was filmed for them or has reviewed them");
    });

    test("help answers whether Plus can be bought", async ({ page }) => {
      await page.goto("/help");
      const answer = page.getByTestId("help-plus-answer");
      await expect(answer).toHaveAttribute("data-billing-state", state.name);
      await expect(answer).toContainText(EXPECT[state.name].billing);
      await expect(answer).not.toContainText(EXPECT[state.name].not);
      await expect(page.getByTestId("help-classes")).toContainText(/generated by AI[\s\S]*narration, captions and chapters/);
    });

    test("/plus labels checkout for this state", async ({ page }) => {
      await page.goto("/plus");
      await expect(page.getByTestId("billing-status")).toHaveAttribute("data-billing-state", state.name);
      await expect(page.getByTestId("plan-card-plus")).toContainText("$9.99/mo");
      await expect(page.getByTestId("plan-card-plus")).not.toContainText(/filmed|offline/i);
      await expect(page.getByTestId("plan-card-plus")).toContainText("AI-generated instructor motion");
      const intro = page.getByTestId("plans-intro");
      const status = page.getByTestId("plus-account-status");
      const select = page.getByTestId("plan-select-plus");
      const badge = page.getByTestId("plan-billing-badge-plus");
      if (state.name === "disabled") {
        await expect(intro).toContainText(/unavailable/);
        await expect(badge).toHaveText("Not on sale");
        await expect(select).toHaveText("Subscribe");
        await expect(status).toContainText(/unavailable/);
      } else if (state.name === "test") {
        await expect(intro).toContainText("Test checkout — no real charges.");
        await expect(badge).toHaveText("Test checkout");
        await expect(select).toHaveText("Subscribe (test checkout)");
        await expect(status).toContainText(/test mode — no real charges/);
      } else {
        await expect(intro).not.toContainText(/test|unavailable/i);
        await expect(badge).toHaveCount(0);
        await expect(select).toHaveText("Subscribe");
        await expect(select).toBeEnabled();
        await expect(page.getByTestId("paywall-root")).not.toContainText(/test mode|no real charges/i);
      }
    });
  });
}
